"""Whether the text GitHub holds is the text sent (keyword: landed, pitboss#531)."""

from .totaljson import text

HOST_FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"
FOOTERS = (HOST_FOOTER,)
CARET = {
    code: "^" + chr(code ^ 64) for code in (*range(9), 11, 12, *range(14, 32), 127)
}


def same(left: object, right: str) -> bool:
    """Whether a text GitHub holds is the one that was sent.

    Args:
        left: what GitHub holds.
        right: what was sent.

    Returns:
        True when it holds the text sent, a line end and the ends' blanks apart,
        followed by nothing or by the footer the host adds to what it keeps (a text
        cut short, or one with more after it, is not the text sent).
    """

    def plain(each: str) -> str:
        # the host may write a control character as ``^[`` (caret notation)
        return each.translate(CARET).replace("\r\n", "\n").strip()

    held, sent = plain(text(left)), plain(right)
    return held.startswith(sent) and held[len(sent) :].strip() in ("", *FOOTERS)
