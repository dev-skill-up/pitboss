"""Tests for the session URL every parser ignores (pitboss#109, session-url)."""

import dataclasses
import unittest

from hamcrest import assert_that, equal_to

from .. import (
    config,
    forms,
    gradeline,
    reviews,
    roundlimit,
    sessionurl,
    shapes,
    unreadableform,
)

HEAD = "a" * 40
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
BODY = (
    f"Fixes #12\n\nHead: {HEAD}\n\n## Evidence\n\n```\n$ nox -s tests\nOK\n```\n\n---\n"
)
SESSION = "https://claude.ai/code/session_01HwLsLqpK11q86JDdqHKAzP"
URL_AFTER = f"\n{SESSION}\n"
ROBOT = "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
ROBOT_LINK = f"🤖 Generated with [Claude Code]({SESSION})"
FOOTER_LINK = f"_Generated by [Claude Code]({SESSION})_"
PROSE = f"see {SESSION} for the session"
ACCEPTED_FOOTERS = [ROBOT, FOOTER]
REVIEW_FORM = config.ReviewForm(
    lines=("## Review", "Reviewed: {sha}", "Verdict: {verdict}"),
    approved="approved",
    changes_needed="changes needed",
)
GATED = dataclasses.replace(
    REVIEW_FORM, lines=("## Adversarial review", *REVIEW_FORM.lines[1:])
)
REVIEW_CONFIG = config.Review(
    trusted=frozenset({"MEMBER"}),
    gated=frozenset(),
    form=REVIEW_FORM,
    gated_form=REVIEW_FORM,
)
REVIEW_TEXT = f"## Review\nReviewed: {HEAD}\nVerdict: approved\n"
IN_FORM = REVIEW_TEXT + "Plan: approved\n"
OFF_FORM = "Plan: approved\nVerdict: changes needed\nExecution: wrong\n"


def subject_of(body: str) -> forms.Subject:
    """A text to check, with the head the tests use.

    Args:
        body: the text.

    Returns:
        The subject.
    """
    return forms.Subject(name="x", body=body, head=HEAD)


def body_findings(body: str) -> int:
    """How many findings the PR body check makes of a text.

    Args:
        body: the text.

    Returns:
        The number of findings.
    """
    return len(forms.pr_body(subject_of(body), ACCEPTED_FOOTERS))


def unreadable_count(body: str) -> int:
    """How many findings the sweep makes of one comment.

    Args:
        body: the comment's text.

    Returns:
        The number of UNREADABLE REVIEW findings.
    """
    posted = [
        shapes.Comment(body=body, author_association="MEMBER", created_at="1", url="u")
    ]
    _, form = reviews.rules(REVIEW_CONFIG, "o/x")
    found = unreadableform.find(
        posted, REVIEW_CONFIG.trusted, form, reviews.line_pattern
    )
    return len(found)


class TestStrip(unittest.TestCase):
    """The one function that removes the session URL."""

    def test_removed_forms(self) -> None:
        """A URL line, even the last one without a newline, and a link suffix."""
        link = "🤖 Generated with [Claude Code](https://claude.ai/code)"
        cases = {f"a\n{SESSION}\nb\n": "a\nb\n", f"a\n  {SESSION}  ": "a\n"}
        cases[ROBOT_LINK] = link
        for text, wanted in cases.items():
            assert_that(sessionurl.strip(text), equal_to(wanted))

    def test_prose_mention_is_kept(self) -> None:
        """A session URL inside prose is text like any other."""
        assert_that(sessionurl.strip(PROSE), equal_to(PROSE))


class TestBodies(unittest.TestCase):
    """A PR body reads the same with or without the session URL."""

    def test_pr_body_reads_the_same(self) -> None:
        """A trailing URL line and the URL inside the footer link change nothing."""
        plain = BODY + FOOTER + "\n"
        tails = (
            plain + URL_AFTER,
            BODY + FOOTER_LINK + "\n",
            plain + "\n" + SESSION,
        )
        for each in tails:
            assert_that(
                forms.pr_body(subject_of(each), ACCEPTED_FOOTERS),
                equal_to(forms.pr_body(subject_of(plain), ACCEPTED_FOOTERS)),
            )

    def test_a_missing_footer_is_still_refused(self) -> None:
        """The URL line is not a footer."""
        assert_that(body_findings(BODY + URL_AFTER), equal_to(1))

    def test_prose_mention_is_not_stripped(self) -> None:
        """A footer followed by prose still passes; prose alone is no footer."""
        kept = BODY + ROBOT + "\n" + PROSE + "\n"
        assert_that(body_findings(kept), equal_to(0))
        assert_that(body_findings(BODY + PROSE + "\n"), equal_to(1))

    def test_url_first_line_is_absent(self) -> None:
        """The first line is the first line that is not the URL."""
        assert_that(
            forms.pr_body(subject_of(SESSION + "\nFixes #1\n"), []),
            equal_to(forms.pr_body(subject_of("Fixes #1\n"), [])),
        )


class TestReviews(unittest.TestCase):
    """A review comment reads the same with or without the session URL."""

    def test_review_form_checks(self) -> None:
        """The ordinary and the gated form check read it as without."""
        text = f"## Adversarial review\n\nReviewed: {HEAD}\nVerdict: approved\n"
        for variant in (text + URL_AFTER, text + FOOTER_LINK + "\n"):
            for check in (forms.ordinary_review, forms.gated_review):
                assert_that(
                    check(subject_of(variant), GATED),
                    equal_to(check(subject_of(text), GATED)),
                )

    def test_readers(self) -> None:
        """Both readers find the review and the plain check passes."""
        for read in (reviews.read_comment, reviews.read_gated):
            plain = read(REVIEW_TEXT, REVIEW_FORM)
            assert_that(read(REVIEW_TEXT + URL_AFTER, REVIEW_FORM), equal_to(plain))
            assert_that(plain is None, equal_to(False))
        assert_that(reviews.is_plain(REVIEW_TEXT + URL_AFTER), equal_to(True))

    def test_grade_line_after_the_url_line(self) -> None:
        """A Plan line is a grade with the URL line above it."""
        found = gradeline.line_approved(
            sessionurl.strip(f"{SESSION}\nPlan: approved\n"),
            "Plan: ",
            "approved",
            "changes needed",
        )
        assert_that(found, equal_to(True))
        grade = roundlimit.plan_grade(f"{SESSION}\nPlan: approved\n", REVIEW_FORM)
        assert_that(grade is None, equal_to(False))

    def test_ruling_first_line(self) -> None:
        """The first line of a ruling is the first line that is not the URL."""
        ruling = f"{SESSION}\nOpus ruling\nx\n"
        assert_that(roundlimit.is_ruling(ruling), equal_to(True))
        assert_that(roundlimit.is_ruling(f"{PROSE}\nOpus ruling\n"), equal_to(False))


class TestUnreadable(unittest.TestCase):
    """UNREADABLE REVIEW does not see the session URL."""

    def test_url_line_does_not_change_the_first_line(self) -> None:
        """A review in the form stays readable, one off it stays unreadable."""
        assert_that(unreadable_count(IN_FORM + URL_AFTER), equal_to(0))
        assert_that(unreadable_count(SESSION + "\n" + IN_FORM), equal_to(0))
        assert_that(unreadable_count(OFF_FORM + URL_AFTER), equal_to(1))

    def test_a_comment_of_only_the_url_is_no_review(self) -> None:
        """It grades nothing."""
        assert_that(unreadable_count(SESSION + "\n"), equal_to(0))
