HEAD = "a" * 40
OTHER = "b" * 40
ADDRESS = "https://github.com/owner/project/actions/runs/{run}"
POINTER = "workflow `check.yml`, job `tests`, step `Run Nox`, " + ADDRESS + "/job/9"
PLAN = "## Plan\n1. " + POINTER.format(run=5) + "\n"
ITEMS = ["First item.", "Second item, counted by `rg -c code src`."]
# the command each item's row runs: the second item names its measurement
ROW_COMMANDS = {1: "git status", 2: "rg -c code src"}
TICKET = "Text.\n\n## Done when\n\n" + "".join(f"- {each}\n" for each in ITEMS)
DIGEST = ticketwhen.digest(TICKET)
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
# comments that say "Added to the Done-when": they add nothing (pitboss#396)
COMMENTS = [
    "Added to the Done-when (2026-11-08 17:45Z; seen on PR 372): a comment's own"
    " item." + FOOTER,
    "Added to Done when:\n* A bullet\n* Another bullet" + FOOTER,
]
Heads = Mapping[tuple[str, int], str]


def mentions(found: Sequence[str], words: Sequence[Sequence[str]]) -> bool:
    """Whether each finding has the words expected of it, and no other is there.

    Args:
        found: the findings.
        words: for each finding expected, the words it has.

    Returns:
        True when there are as many findings, each with its words.
    """
    return len(found) == len(words) and all(
        all(word in each for word in some) for each, some in zip(found, words)
    )


def said(lines: Sequence[str], check: str, words: Sequence[Sequence[str]]) -> bool:
    """Whether the lines of one check are exactly the findings expected.

    Args:
        lines: the lines plan-check printed.
        check: the name of the check, as a finding starts with it.
        words: for each finding expected, the words it has.

    Returns:
        The answer of ``mentions`` for the lines that start with the check.
    """
    return mentions([each for each in lines if each.startswith(check)], words)


def read_from(heads: Heads) -> cirun.HeadOf:
    """A reader of the head of a run.

    Args:
        heads: the head of each run, by repository and id.

    Returns:
        The reader; None for a run it does not have.
    """
    return lambda slug, run: heads.get((slug, run))


# each case: the Plan, the head of the body, the heads of the runs, the words of
# each finding expected
RUNS: Mapping[str, tuple[str, str, Heads, Sequence[Sequence[str]]]] = {
    "another commit's run": (
        PLAN,
        HEAD,
        {("owner/project", 5): OTHER},
        [["ci-run:", "Plan line 2", "runs/5", OTHER, HEAD]],
    ),
    "the head's run": (PLAN, HEAD, {("owner/project", 5): HEAD}, []),
    "a run that cannot be read": (PLAN, HEAD, {}, [["which cannot be read"]]),
    "a head that is no SHA": (PLAN, "HEAD", {("owner/project", 5): OTHER}, []),
    "a row that is no pointer": (
        "## Plan\n1. `rg x`, see " + ADDRESS.format(run=5) + "\n",
        HEAD,
        {("owner/project", 5): OTHER},
        [],
    ),
}


class TestRunHead(unittest.TestCase):
    """The run a CI pointer names is the run of the body's head."""

    def test_each_case(self) -> None:
        """Done-when: another commit's run is refused, the head's passes."""
        for name, (plan, head, served, words) in RUNS.items():
            with self.subTest(name):
                found = cirun.findings(plan, head, read_from(served))
                assert_that(mentions(found, words), equal_to(True))

    def test_a_run_named_twice_is_read_once(self) -> None:
        """The same address, as a run and as a job of it, in one row."""
        seen: list[int] = []

        def reading(slug: str, run: int) -> str | None:
            seen.append(run)
            return HEAD

        address = ADDRESS.format(run=5)
        row = (
            f"## Plan\n1. workflow `check.yml`, step `Run Nox`, {address}/job/9"
            f" {address}"
        )
        cirun.findings(row, HEAD, reading)
        assert_that(seen, equal_to([5]))


BODIES: Mapping[str, object] = {
    "repos/o/p/actions/runs/1": {"head_sha": HEAD},
    "repos/o/p/actions/runs/2": {"status": "queued"},
    "repos/o/p/actions/runs/3": ["not", "a", "run"],
}
REMOTES = {
    "https://github.com/o/p.git": "o/p",
    "git@github.com:o/p": "o/p",
    "https://github.com/o/p/": "o/p",
    "/tmp/clone": "",
}


class TestReaders(unittest.TestCase):
    """The reads of GitHub."""

    def test_the_head_of_a_run(self) -> None:
        """A run, a run without a head, a run that is no object, no run."""
        read = plantickets.run_head(fakes.github(dict(BODIES)))
        found = [read("o/p", each) for each in (1, 2, 3, 4)]
        assert_that(found, equal_to([HEAD, None, None, None]))

    def test_the_slug_of_a_remote(self) -> None:
        """The forms git prints."""
        found = {each: plantickets.slug_of(each + "\n") for each in REMOTES}
        assert_that(found, equal_to(REMOTES))


def plan_holding(*drop: int) -> str:
    """A Plan with each Done-when item in a numbered row, less the dropped rows.

    Args:
        *drop: the numbers of the items to leave out.

    Returns:
        The Plan section.
    """
    rows = [
        f"{number}. {each} Run `{ROW_COMMANDS[number]}`."
        for number, each in enumerate(ITEMS, 1)
        if number not in drop
    ]
    return "## Plan\n" + "\n".join(rows)


def clone_head(here: world.World) -> str:
    """The commit the world's clone is at.

    Args:
        here: the world.

    Returns:
        Its SHA.
    """
    return run_git(here.clone, "rev-parse", "HEAD").strip()


def put_ticket(here: world.World, number: int, ticket: str) -> None:
    """Give the fake GitHub a ticket of ``owner/project`` and its comments.

    The comments are there to be read: a read of them would be seen.

    Args:
        here: the world.
        number: the ticket's number.
        ticket: its text.
    """
    base = f"repos/owner/project/issues/{number}"
    here.bodies[base] = {"body": ticket}
    listed = [{"id": 1, "html_url": "u", "body": each} for each in COMMENTS]
    here.bodies[fakes.page(f"{base}/comments")] = listed


def full_plan() -> str:
    """A Plan with every item of the Done-when, each in a row of its own.

    Returns:
        The Plan section.
    """
    return plan_holding()


def run_check(
    here: world.World,
    fixes: str,
    plan: str,
    *options: str,
    digest: str = DIGEST,
) -> Sequence[str]:
    """Run ``pitboss plan-check`` on a body and give the lines it printed.

    Args:
        here: the world.
        fixes: what follows ``Fixes `` in the body's first line.
        plan: the Plan section.
        *options: options after the file.
        digest: the Done-when digest the body records; empty for no line.

    Returns:
        The lines of the output, the exit status first.
    """
    line = f"Done-when digest: {digest}\n\n" if digest else ""
    head = f"Fixes {fixes}\n\nHead: {clone_head(here)}\n\n{line}"
    path = write_text("body.txt", f"{head}{plan}\n\n## Execution\nx\n")
    done = world.invoke(here, "plan-check", path, "--repo", str(here.clone), *options)
    return [str(done.code), *done.out.splitlines()]


def ticket_world() -> world.World:
    """A world whose fake GitHub has the ticket ``owner/project#9``.

    Returns:
        The world.
    """
    here = world.make_world()
    put_ticket(here, 9, TICKET)
    return here


def with_pointer(plan: str) -> str:
    """A Plan with a CI pointer row, after the rows of the items, that names run 5.

    Args:
        plan: the Plan.

    Returns:
        The Plan and a last row.
    """
    return plan + f"\n{len(ITEMS) + 1}. " + POINTER.format(run=5)


OPTION = ("--repository", "owner/project")
Make = Callable[[], world.World]
# each case: how to make the world, the first line of the body, how to make the
# Plan, the options and the words of the plan-done-when finding expected
Case = tuple[Make, str, Callable[[], str], Sequence[str], Sequence[Sequence[str]]]
COMMANDS: Mapping[str, Case] = {
    "a plan with the done-when": (ticket_world, "owner/project#9", full_plan, (), []),
    "a narrowed plan": (
        ticket_world,
        "owner/project#9",
        lambda: plan_holding(2),
        (),
        [["Second item, counted by"]],
    ),
    "a bare number and the repository option": (
        ticket_world,
        "#9",
        lambda: plan_holding(1),
        OPTION,
        [["First item."]],
    ),
    "a ticket that cannot be read": (
        world.make_world,
        "owner/project#99",
        full_plan,
        (),
        [["owner/project#99 cannot be read"]],
    ),
    "a bare number with no repository": (
        ticket_world,
        "#9",
        full_plan,
        (),
        [["names no repository"]],
    ),
}
# each case: the head of the run the pointer names (empty: the clone's head) and
# whether the check refuses it
RUN_CASES: Mapping[str, tuple[str, bool]] = {
    "the previous commit's run": (OTHER, True),
    "the head's run": ("", False),
}


class TestCommand(unittest.TestCase):
    """``pitboss plan-check`` reads the ticket and the run."""

    def test_each_case(self) -> None:
        """Done-when: the ticket's Done-when is read from its body."""
        for name, (make, fixes, plan, options, words) in COMMANDS.items():
            with self.subTest(name):
                lines = run_check(make(), fixes, plan(), *options)
                assert_that(said(lines, "plan-done-when:", words), equal_to(True))

    def test_the_comments_are_never_read(self) -> None:
        """Done-when: no call asks for the ticket's comments, and they add nothing."""
        here = ticket_world()
        lines = run_check(here, "owner/project#9", full_plan())
        assert_that(lines[0], equal_to("0"))
        asked = " ".join(" ".join(each) for each in here.calls)
        assert_that("/comments" in asked, equal_to(False))

    def test_the_verdict_counts_the_done_when(self) -> None:
        """Done-when: a narrowed Plan is refused, exit status 1."""
        lines = run_check(ticket_world(), "owner/project#9", plan_holding(2))
        assert_that(lines[0], equal_to("1"))
        assert_that("Done-when findings: 1" in lines[-1], equal_to(True))

    def test_a_done_when_edited_after_the_start_is_refused(self) -> None:
        """Done-when: the body records the start's digest, the ticket is now other."""
        here = world.make_world()
        put_ticket(here, 9, TICKET + "- A third item.\n")
        lines = run_check(here, "owner/project#9", full_plan())
        words = [["edited after a worker started", DIGEST]]
        assert_that(said(lines, "done-when-edited:", words), equal_to(True))
        assert_that(lines[0], equal_to("1"))
        assert_that("Done-when edit findings: 1" in lines[-1], equal_to(True))

    def test_a_body_with_no_digest_line_is_refused(self) -> None:
        """Done-when: no line, no record that the Done-when was not edited."""
        lines = run_check(ticket_world(), "owner/project#9", full_plan(), digest="")
        words = [["no `Done-when digest: " + DIGEST]]
        assert_that(said(lines, "done-when-edited:", words), equal_to(True))

    def test_a_measurement_a_row_does_not_run_is_refused(self) -> None:
        """Done-when: the second row runs another command than the ticket names."""
        plan = plan_holding().replace("Run `rg -c code src`.", "Run `rg -c other src`.")
        lines = run_check(ticket_world(), "owner/project#9", plan)
        words = [["`rg -c code src`"]]
        assert_that(said(lines, "plan-measurement:", words), equal_to(True))
        assert_that("Measurement findings: 1" in lines[-1], equal_to(True))

    def test_the_run_of_another_commit_is_refused(self) -> None:
        """Done-when: a pointer run of the previous commit; the head's passes."""
        for name, (head, refused) in RUN_CASES.items():
            with self.subTest(name):
                here = ticket_world()
                shown = head or clone_head(here)
                here.bodies["repos/owner/project/actions/runs/5"] = {"head_sha": shown}
                lines = run_check(here, "owner/project#9", with_pointer(full_plan()))
                assert_that(said(lines, "ci-run:", [[]]), equal_to(refused))
