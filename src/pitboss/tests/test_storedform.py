"""Tests: lint pr-body on a stored body equals the file (keyword: store-form, #164)."""

import unittest
from typing import Sequence

from hamcrest import assert_that, equal_to

from .. import evidence, expansion, forms
from .formchecks import subject
from .linting import HEAD

URL = "https://x.example/a?b=1"
ROBOT = "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
STORE_FOOTER = "_Generated by [Claude Code](https://claude.ai/code/session_01Abc)_"
# lines of a block as a log prints them: a BOM, carriage returns, a bare URL
LINES = f"$ gh run view\n﻿Redirecting to {URL}\r\nok\r\n"
HEADER = f"Fixes #164\n\nHead: {HEAD}\n\n## Evidence\n\n"
FILE = f"{HEADER}```{expansion.info(LINES)}\n{LINES}```\n\n{ROBOT}\n"
# the body as the store keeps it: the BOM and the CRs gone, the URL wrapped in
# double backticks, the footer replaced
STORED_LINES = f"$ gh run view\nRedirecting to ``{URL}``\nok\n"
STORED = (
    f"{HEADER}```{expansion.info(LINES)}\n{STORED_LINES}```\n\n---\n{STORE_FOOTER}\n"
)


def findings(body: str) -> Sequence[str]:
    """The findings of the whole pr-body form on a text.

    Args:
        body: the text.

    Returns:
        What ``forms.pr_body`` finds, with only the robot footer configured.
    """
    return forms.pr_body(subject(body), (ROBOT,))


class TestStoredBody(unittest.TestCase):
    """A body with the three rewrites gets the result the file got."""

    def test_the_form_gives_the_same_result(self) -> None:
        """BOM, wrapped URL and replaced footer: both pass, and so do both."""
        assert_that(findings(STORED), equal_to(findings(FILE)))
        assert_that(findings(FILE), equal_to([]))

    def test_an_edited_stored_block_is_refused(self) -> None:
        """A changed line of the stored block is not a store rewrite."""
        edited = STORED.replace("ok\n", "fine\n")
        assert_that(evidence.hand_typed(edited), equal_to([8]))
