"""``pitboss format plan`` and ``format body``: text from JSON (keyword: plan-format).

The Plan's JSON is in the form of ``planformat.schema.json``; the command rows are
numbered first, so row N is the row of the Nth Evidence block (``plan-row``).
``format body`` makes a whole PR body from a JSON in the form of
``bodyformat.schema.json`` (its ``plan`` is the Plan's), in the form ``lint pr-body``
takes. It has ``Fixes``, ``Head:`` (the checkout's, never the JSON's), the digest,
the Plan, the Execution, the Evidence the Plan's commands ran and one footer. The
body is printed only when ``forms.pr_body`` finds nothing in it, so a JSON the
schema takes and the parser refuses is refused with the parser's findings and prints
no body (keyword: body-format).
"""

import argparse
import functools
import pathlib
import re
import sys
from typing import Iterator, Mapping, Sequence

from gather.commands import add_argument

from . import (
    ENTRY_DATA,
    expand_commands,
    expansion,
    forms,
    noxrow,
    plancheck,
    plandigest,
    totalbody,
)
from .totaljson import JsonMap, listing, members, read_file, text

SCHEMA = "planformat.schema.json"
BODY_SCHEMA = "bodyformat.schema.json"
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
NAME = "body"
MACHINE = totalbody.MACHINE_PATH
HEAD_ROW: JsonMap = {"item": "The head.", "command": "git rev-parse HEAD"}
TYPES: Mapping[str, type] = {"object": dict, "array": list, "string": str}
CI = "CI: workflow `{workflow}`, job `{job}`, step `{step}`, greppable `{grep}`."


def schema(name: str = SCHEMA) -> JsonMap:
    """The schema a ``format`` kind reads its JSON by.

    Args:
        name: the schema's file in the package (the Plan's by default).

    Returns:
        The schema, as the repository holds it.
    """
    return members(read_file(pathlib.Path(__file__).with_name(name)))


def _object(value: JsonMap, rules: JsonMap, where: str) -> Iterator[str]:
    for key in listing(rules.get("required")):
        if text(key) not in value:
            yield f"{where}.{text(key)}: missing".lstrip(".")
    fields = members(rules.get("properties"))
    for key, each in value.items():
        if key in fields:
            yield from refusals(
                each, members(fields[key]), f"{where}.{key}".lstrip(".")
            )
        elif rules.get("additionalProperties") is False:
            yield f"{where}.{key}: not a field of the schema".lstrip(".")


def refusals(value: object, rules: JsonMap, where: str = "") -> Iterator[str]:
    """Why a JSON value is not in the form of a schema.

    Args:
        value: the value.
        rules: the schema (or the part of it for the value).
        where: the value's field (``rows[0].item``), "" for the whole.

    Yields:
        Each refusal, the field at fault first.
    """
    kind = text(rules.get("type"))
    if kind and not isinstance(value, TYPES[kind]):
        yield f"{where or '(the file)'}: not a JSON {kind}"
        return
    pattern = text(rules.get("pattern"))
    if pattern and not re.search(pattern, text(value)):
        yield f"{where}: does not match {pattern}"
    if isinstance(value, dict):
        yield from _object(value, rules, where)
    yield from _array(listing(value), rules, where)
    choices = [members(each) for each in listing(rules.get("oneOf"))]
    if choices and sum(not any(refusals(value, each)) for each in choices) != 1:
        names = [text(key) for each in choices for key in listing(each["required"])]
        yield f"{where}: has not exactly one of {', '.join(names)}"


def _array(items: Sequence[object], rules: JsonMap, where: str) -> Iterator[str]:
    least = rules.get("minItems")
    if isinstance(least, int) and len(items) < least:
        yield f"{where}: fewer than {least} items"
    for index, each in enumerate(items):
        yield from refusals(each, members(rules.get("items")), f"{where}[{index}]")


def _row(row: JsonMap) -> str:
    if "command" in row:
        return f"{text(row['item'])} Evidence: `{text(row['command'])}`"
    return f"{text(row['item'])} {CI.format(**members(row['ci']))}"


def _plan_rows(plan: JsonMap) -> Sequence[JsonMap]:
    return [members(each) for each in listing(plan.get("rows"))]


def section(plan: JsonMap) -> str:
    """The Plan section of a JSON the schema takes.

    Args:
        plan: the JSON.

    Returns:
        The ``## Plan`` heading, the intro, then the rows, the command rows first.
    """
    ordered = sorted(_plan_rows(plan), key=lambda each: "command" not in each)
    numbered = [f"{number}. {_row(each)}" for number, each in enumerate(ordered, 1)]
    intro = [text(plan["intro"]), ""] if "intro" in plan else []
    return "\n".join(["## Plan", "", *intro, *numbered]) + "\n"


def _command_refusals(number: int, command: str) -> Sequence[str]:
    where = f"rows[{number}].command"
    return [
        *([f"{where}: runs nox: give the CI pointer"] * noxrow.runs_nox(command)),
        *([f"{where}: names a path of one machine"] * bool(MACHINE.search(command))),
    ]


def _each_command(rows: Sequence[JsonMap]) -> Sequence[str]:
    return [
        found
        for number, each in enumerate(rows)
        for found in _command_refusals(number, text(each.get("command")))
    ]


def plan_refusals(value: object) -> Sequence[str]:
    """Why a JSON value is not a Plan in the schema's form.

    Beside the schema, a command that runs nox or names a path of one machine is
    refused (the Plan's evidence is CI's for nox, and a reviewer's container has
    no such path: keywords plan-nox and machine-path).

    Args:
        value: the JSON.

    Returns:
        Each refusal, the field at fault first.
    """
    found = refusals(value, schema())
    return [*found, *_each_command(_plan_rows(members(value)))]


def body_refusals(value: object) -> Sequence[str]:
    """Why a JSON value is not a body in the schema's form.

    Args:
        value: the JSON.

    Returns:
        Each refusal, the field at fault first; the Plan's under ``plan``.
    """
    own = list(refusals(value, members(schema(BODY_SCHEMA))))
    plan = members(value).get("plan")
    inner = [f"plan.{each}" for each in plan_refusals(plan)]
    return [*own, *(inner if isinstance(plan, dict) else [])]


def body_plan(value: JsonMap) -> JsonMap:
    """The body's Plan, its first row the head.

    Args:
        value: a JSON the schema takes.

    Returns:
        The JSON's Plan with a row that runs ``git rev-parse HEAD`` before the
        others, so the Evidence always has a block ``expand`` produced.
    """
    plan = members(value["plan"])
    return {**plan, "rows": [HEAD_ROW, *listing(plan.get("rows"))]}


def plan_commands(plan: JsonMap) -> Sequence[str]:
    """The commands of a Plan's rows, in the order of their rows.

    Args:
        plan: a Plan the schema takes.

    Returns:
        The commands, the Evidence's order.
    """
    return [text(each["command"]) for each in _plan_rows(plan) if "command" in each]


def _prefixed(prefix: str, items: Sequence[str]) -> Sequence[str]:
    return [f"{prefix}{each}" for each in items]


def body_template(value: JsonMap, head: str) -> str:
    """The body, its commands not yet run.

    Args:
        value: a JSON the schema takes.
        head: the checkout's head.

    Returns:
        The text ``expansion.expand`` runs.
    """
    plan = body_plan(value)
    steps = _prefixed("- ", [text(each) for each in listing(value["execution"])])
    runs = _prefixed("$ ", plan_commands(plan))
    top = [
        f"Fixes {text(value['ticket'])}",
        "",
        f"Head: {head}",
        "",
        text(value["summary"]),
        "",
        f"Done-when digest: {text(value['digest'])}",
        "",
    ]
    middle = [section(plan).rstrip("\n"), "", "## Execution", "", *steps, ""]
    return "\n".join([*top, *middle, "## Evidence", "", *runs, "", FOOTER, ""])


def make_body(value: JsonMap, shell: expansion.Shell, head: str) -> str:
    """The body of a JSON, run and read by the parser.

    Args:
        value: a JSON the schema takes.
        shell: runs one command line.
        head: the checkout's head.

    Returns:
        The body, with no finding of ``forms.pr_body``.

    Raises:
        ValueError: the parser's findings, one on each line.
    """
    template = body_template(value, head)
    # keyword: body-injection: expand runs each line that starts `$ `, the Plan's only
    if list(expansion.commands(template)) != list(plan_commands(body_plan(value))):
        raise ValueError(f"{NAME}: a field starts a line with `$ `: it would run")
    made = expansion.expand(template, shell, head)
    if found := body_findings(made, head):
        raise ValueError("\n".join(found))
    return made


def body_findings(made: str, head: str) -> Sequence[str]:
    """What the checks of the body's own text find in it, that no network is needed for.

    The checks are ``lint pr-body``'s, the rows of the body (the head, a path of one
    machine) and ``plan-check``'s that read the body and nothing else: a Plan row
    that runs nox is refused, and a numbered row has a command, a read or a CI
    pointer. Each command is taken as run (the checks read the text).

    Args:
        made: the body.
        head: the checkout's head.

    Returns:
        Each finding; none for a body the parser takes.
    """
    section = plandigest.section(made)
    rows, refused, _ = plancheck.report(
        section, lambda each: plancheck.finished(0, 0.0)
    )
    return [
        *forms.pr_body(forms.Subject(name=NAME, body=made, head=head)),
        *totalbody.body_findings(made, head),
        *[f"{NAME}: {rows[number - 1]}" for number in refused],
        *plancheck.form_findings(made, section, []),
    ]


def _refused_or(args: argparse.Namespace) -> object:
    # the file's JSON; the faults of its kind's schema end the command (exit 1)
    try:
        found = read_file(pathlib.Path(args.file))
    except (OSError, ValueError) as error:
        print(f"{args.file}: {error}", file=sys.stderr)
        raise SystemExit(1)
    refused = plan_refusals(found) if args.kind == "plan" else body_refusals(found)
    if listed := [f"{args.file}: {each}" for each in refused]:
        print(*listed, sep="\n", file=sys.stderr)
        raise SystemExit(1)
    return found


@ENTRY_DATA.register(
    add_argument("kind", choices=("plan", "body"), help="the text: plan or body"),
    add_argument("file", help="the JSON, in the form of the kind's schema file"),
    add_argument(
        "--cwd",
        default=".",
        help="body: the checkout the Plan's commands run in (default: the current"
        " directory)",
    ),
    name="format",
)
def format_section(args: argparse.Namespace) -> None:
    """Print the Plan section or the body of a JSON file; exit 1 naming each fault.

    Args:
        args: the parsed arguments.

    Raises:
        SystemExit: a file that is no JSON, a JSON the schema refuses, or (for a
            body) a body the parser finds fault in.
    """
    found = _refused_or(args)
    if args.kind == "plan":
        print(section(members(found)), end="")
        return
    shell = functools.partial(expand_commands.run_in, args, pathlib.Path(args.cwd))
    try:
        print(make_body(members(found), shell, expand_commands.head_of(args)), end="")
    except ValueError as error:
        print(error, file=sys.stderr)
        raise SystemExit(1)
