class TestReaders(unittest.TestCase):
    """The reads of GitHub."""

    def test_the_head_of_a_run(self) -> None:
        """A run, a run without a head, a run that is no object, no run."""
        read = plantickets.run_head(fakes.github(dict(BODIES)))
        found = [read("o/p", each) for each in (1, 2, 3, 4)]
