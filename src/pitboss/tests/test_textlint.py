"""Tests for the text-lint status and ``lint event``."""

import json
import unittest
from typing import Mapping, Sequence

from hamcrest import (
    assert_that,
    contains_string,
    equal_to,
    greater_than,
    has_length,
    less_than_or_equal_to,
)

from .fakes import directory
from .linting import lines, lint, write_text

HEAD = "a" * 40
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
BODY = f"""Fixes #12

Head: {HEAD}

## Evidence

```
$ nox -s tests
OK
```

---
{FOOTER}
"""

URL = "https://example.test/run/1"


def event(
    body: object = BODY,
    branch: str = "fix-1",
    author: str = "someone",
    head: str = HEAD,
) -> str:
    """Make a pull request event.

    Args:
        body: the pull request's body.
        branch: its head branch.
        author: who opened it.
        head: its head SHA.

    Returns:
        The event's JSON.
    """
    pull = {
        "body": body,
        "head": {"sha": head, "ref": branch},
        "user": {"login": author},
    }
    return json.dumps({"action": "opened", "pull_request": pull})


def run(text: str, *options: str) -> tuple[object, str, str, Sequence[str]]:
    """Run ``pitboss lint event``.

    Args:
        text: the event's JSON.
        *options: options after the files.

    Returns:
        The exit code, the standard error, the status file's text (empty when
        none was written) and the lines printed.
    """
    status = directory() / "status.json"
    ran = lint("event", write_text("event.json", text), str(status), *options)
    written = status.read_text() if status.exists() else ""
    return ran.code, ran.err, written, lines(ran)


def posted(text: str, *options: str) -> tuple[object, Mapping[str, str], Sequence[str]]:
    """Run ``lint event`` and read the status it wrote.

    Args:
        text: the event's JSON.
        *options: options after the files.

    Returns:
        The exit code, the status and the lines printed.
    """
    code, _, written, shown = run(text, *options)
    return code, json.loads(written), shown


class TestStatus(unittest.TestCase):
    """What the status says."""

    def test_in_form(self) -> None:
        """A body in form is success, with the log's address."""
        code, status, shown = posted(event(), "--url", URL)
        assert_that(code, equal_to(0))
        assert_that(
            status,
            equal_to(
                {
                    "state": "success",
                    "context": "text-lint",
                    "description": "ok",
                    "target_url": URL,
                }
            ),
        )
        assert_that(shown, equal_to(["text-lint: success: ok"]))

    def test_first_finding(self) -> None:
        """A body out of form is failure with the first finding, all printed."""
        code, status, shown = posted(event("Refs #1\n"))
        assert_that(code, equal_to(0))
        assert_that(status["state"], equal_to("failure"))
        assert_that(status["description"], contains_string("(first-line)"))
        assert_that(len(status["description"]), less_than_or_equal_to(140))
        assert_that(shown[0], contains_string("first-line"))
        assert_that(shown[-1], contains_string("text-lint: failure: body: "))
        assert_that(len(shown), greater_than(1))

    def test_phrase_and_missing_body(self) -> None:
        """The banned phrases are read, and a null body is an empty one."""
        phrase = BODY + "\nmy provisional verdict is approved\n"
        _, status, shown = posted(event(phrase))
        _, empty, _ = posted(event(None))
        assert_that(" ".join(shown), contains_string("provisional verdict"))
        assert_that(status["state"], equal_to("failure"))
        assert_that(empty["description"], contains_string("first-line"))

    def test_contradiction(self) -> None:
        """Pairs that contradict are findings too."""
        left = "what it cannot run is left to CI and said in the PR"
        right = "what CI runs is not reported as a gap"
        _, both, shown = posted(event(f"{BODY}\n{left}\n{right}\n"))
        _, one, plain = posted(event(f"{BODY}\n{left}\n"))
        assert_that(both["state"], equal_to("failure"))
        assert_that(shown, has_length(3))
        assert_that(one["description"], equal_to("ok"))
        assert_that(plain, equal_to(["text-lint: success: ok"]))

    def test_long_and_non_ascii(self) -> None:
        """A description is cut to 140 characters of ASCII."""
        long_line = "é" * 30 + " my provisional verdict is approved"
        _, status, _ = posted(event(f"{BODY}\n{long_line}\n"))
        assert_that(status["description"], has_length(140))
        assert_that(status["description"].endswith("..."), equal_to(True))
        assert_that(status["description"].isascii(), equal_to(True))

    def test_exempt(self) -> None:
        """A relock branch and a bot are success, saying exempt."""
        bad = "nothing\n"
        found = [
            posted(event(bad, branch="relock/2026-10-29"))[1]["description"],
            posted(event(bad, author="dependabot[bot]"))[1]["description"],
            posted(event(bad, branch="relocked"))[1]["state"],
        ]
        assert_that(found, equal_to(["exempt", "exempt", "failure"]))

    def test_configured_footers(self) -> None:
        """The project's configuration is read with ``--config``."""
        config = write_text(
            "p.toml",
            "[project]\nowner = 'o'\nrepository = 'r'\nmain_clone = '/c'\n"
            "[lint.pr_body]\nfooters = ['-- me']\n",
        )
        _, status, _ = posted(event(), "--config", config)
        assert_that(status["description"], contains_string("(footer)"))


class TestRefusals(unittest.TestCase):
    """What writes no status."""

    def test_unreadable_events(self) -> None:
        """Events that are no pull request event are exit 2, nothing written."""
        cases = [
            "not json",
            "[]",
            json.dumps({"pull_request": {"body": 5}}),
            event().replace('"sha"', '"sha2"'),
            event().replace('"login": "someone"', '"login": 3'),
        ]
        found = [run(each)[::2] for each in cases]
        assert_that(found, equal_to([(2, "")] * len(cases)))

    def test_messages(self) -> None:
        """The message names the file and the problem."""
        messages = [run("not json")[1], run("[]")[1]]
        assert_that(messages[0], contains_string("not JSON"))
        assert_that(messages[1], contains_string("has no pull_request"))

    def test_arguments(self) -> None:
        """Two files are needed, the event must exist, the status writable."""
        good = write_text("e.json", event())
        cases = [
            (good,),
            ("/no/such.json", "/tmp/x.json"),
            (good, "/no/such/dir/s.json"),
        ]
        codes = [lint("event", *each).code for each in cases]
        assert_that(codes, equal_to([2, 2, 2]))
        assert_that(lint("event", *cases[0]).err, contains_string("takes the event"))
        assert_that(lint("event", *cases[2]).err, contains_string("/no/such/dir"))
