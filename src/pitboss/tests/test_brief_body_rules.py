"""The worker briefs state the Plan-row, footer and plan-check rules (#446)."""

import unittest

from .. import brief, brieftextbody
from .briefmake import pinned, text
from .says import has_none
from .test_brief_done_when import WORKERS

ROWS = (
    "Plan rows: one numbered row for each bullet of the Done-when, as the"
    " Done-when line says (its first row is the first bullet, not the whole"
    " Done-when), and each further paragraph of the ticket body that"
    " `plan-check` reads as a Done-when item (a `Not in scope` paragraph) is its"
    " own numbered row with an exact read (a command in backticks, a file in"
    " backticks with what it shows, or a CI pointer)."
)
FOOTER = (
    "Footer: the body ends with exactly one plain footer `_Generated by [Claude"
    " Code](https://claude.ai/code)_`: a body PATCHed with a footer gets two, one"
    " without gets the proxy's; fetch the stored body back and count its"
    " `Generated by` lines and session URLs."
)
CHECK = (
    "Plan check: before the hand-back run `uvx pitboss plan-check BODYFILE --repo"
    " <LOCAL worktree path> --head SHA --config proj` (an `owner/name` for"
    " `--repo` fails with `git worktree add`) and post its raw output as a PR"
    " comment whose first line is `Plan check` and last `Plan check: ok`; without"
    " that comment the sweep offers no review."
)


class TestBodyRules(unittest.TestCase):
    """A worker brief carries the three rules, each as one pinned line."""

    def test_a_start_brief_carries_all_three(self) -> None:
        """Removing one of them from the printed brief fails this test."""
        pinned(brief.Kind.NEW_PR, [ROWS, FOOTER, CHECK])

    def test_every_fix_brief_carries_the_footer_and_the_plan_check(self) -> None:
        """Rules 2 and 3 are in each brief of a fix task."""
        for kind in WORKERS:
            with self.subTest(kind):
                pinned(kind, [FOOTER, CHECK])

    def test_the_constants_are_the_pinned_text(self) -> None:
        """The module holds the lines the brief prints."""
        assert brieftextbody.PLAN_ROWS_DONE_WHEN == ROWS
        assert brieftextbody.FOOTER == FOOTER

    def test_a_brief_that_writes_no_plan_has_no_rows_rule(self) -> None:
        """A CI fix writes no Plan."""
        has_none(text(brief.Kind.FIX_CI), [ROWS])
