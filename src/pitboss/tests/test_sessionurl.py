"""Tests for the session URL every parser ignores (pitboss#109, session-url)."""

import dataclasses
import json
import unittest
from typing import Sequence

from hamcrest import assert_that, contains_string, equal_to, not_

from .. import (
    config,
    flow,
    forms,
    reviews,
    rulings,
    sessionurl,
    shapes,
    unreadableform,
)
from .linting import lint, write_text

HEAD = "a" * 40
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"
BODY = (
    f"Fixes #12\n\nHead: {HEAD}\n\n## Evidence\n\n```\n$ nox -s tests\nOK\n```\n\n---\n"
)
SESSION = "https://claude.ai/code/session_01HwLsLqpK11q86JDdqHKAzP"
URL_AFTER = f"\n{SESSION}\n"
ROBOT = "🤖 Generated with [Claude Code](https://claude.com/claude-code)"
ROBOT_LINK = f"🤖 Generated with [Claude Code]({SESSION})"
FOOTER_LINK = f"_Generated by [Claude Code]({SESSION})_"
PROSE = f"see {SESSION} for the session"
URL_STARTS_PROSE = (
    f"{SESSION} is the session I used\n",
    f"{SESSION}.\n",
    f"{SESSION}, see the log\n",
    f"a\n<{SESSION}\n",
    f"a\n{SESSION}>\n",
)
LINKS_IN_PROSE = (
    f"see [the session]({SESSION}) here\n",
    f"a [Claude Code]({SESSION}) b\n",
    f"[Claude Code]({SESSION})\n",
)
BANNED = "session-line\tsession_\\w+\tsession_x\tNever write the session.\n"
ACCEPTED_FOOTERS = [ROBOT, FOOTER]
REVIEW_FORM = config.ReviewForm(
    lines=("## Review", "Reviewed: {sha}", "Verdict: {verdict}"),
    approved="approved",
    changes_needed="changes needed",
)
GATED = dataclasses.replace(
    REVIEW_FORM, lines=("## Adversarial review", *REVIEW_FORM.lines[1:])
)
REVIEW_CONFIG = config.Review(
    trusted=frozenset({"MEMBER"}),
    gated=frozenset(),
    form=REVIEW_FORM,
    gated_form=REVIEW_FORM,
)
REVIEW_TEXT = f"## Review\nReviewed: {HEAD}\nVerdict: approved\n"
IN_FORM = REVIEW_TEXT + "Plan: approved\n"
OFF_FORM = "Plan: approved\nVerdict: changes needed\nExecution: wrong\n"


def subject_of(body: str) -> forms.Subject:
    """A text to check, with the head the tests use.

    Args:
        body: the text.

    Returns:
        The subject.
    """
    return forms.Subject(name="x", body=body, head=HEAD)


def assert_unchanged(cases: Sequence[str]) -> None:
    """Assert that ``strip`` leaves each text as it is.

    Args:
        cases: the texts.
    """
    for each in cases:
        assert_that(sessionurl.strip(each), equal_to(each))


def body_findings(body: str) -> int:
    """How many findings the PR body check makes of a text.

    Args:
        body: the text.

    Returns:
        The number of findings.
    """
    return len(forms.pr_body(subject_of(body), ACCEPTED_FOOTERS))


def unreadable_count(body: str) -> int:
    """How many findings the sweep makes of one comment.

    Args:
        body: the comment's text.

    Returns:
        The number of UNREADABLE REVIEW findings.
    """
    posted = [
        shapes.Comment(body=body, author_association="MEMBER", created_at="1", url="u")
    ]
    _, form = reviews.rules(REVIEW_CONFIG, "o/x")
    found = unreadableform.find(
        posted, REVIEW_CONFIG.trusted, form, reviews.line_pattern
    )
    return len(found)


class TestStrip(unittest.TestCase):
    """The one function that removes the session URL."""

    def test_removed_forms(self) -> None:
        """A URL line, even the last one without a newline, and a link suffix."""
        link = "🤖 Generated with [Claude Code](https://claude.ai/code)"
        cases = {f"a\n{SESSION}\nb\n": "a\nb\n", f"a\n  {SESSION}  ": "a\n"}
        cases[ROBOT_LINK] = link
        for text, wanted in cases.items():
            assert_that(sessionurl.strip(text), equal_to(wanted))

    def test_prose_mention_is_kept(self) -> None:
        """A session URL in or at the start of a prose line stays."""
        assert_unchanged((PROSE, *URL_STARTS_PROSE))

    def test_links_outside_the_footer_are_kept(self) -> None:
        """Only the generated-by footer's link loses its session suffix."""
        assert_unchanged(LINKS_IN_PROSE)

    def test_angle_pair_is_removed(self) -> None:
        """A URL line in a balanced pair of angle brackets is removed."""
        assert_that(sessionurl.strip(f"a\n<{SESSION}>\nb\n"), equal_to("a\nb\n"))


class TestBodies(unittest.TestCase):
    """A PR body reads the same with or without the session URL."""

    def test_pr_body_reads_the_same(self) -> None:
        """A trailing URL line and the URL inside the footer link change nothing."""
        plain = BODY + FOOTER + "\n"
        tails = (
            plain + URL_AFTER,
            BODY + FOOTER_LINK + "\n",
            plain + "\n" + SESSION,
        )
        for each in tails:
            assert_that(
                forms.pr_body(subject_of(each), ACCEPTED_FOOTERS),
                equal_to(forms.pr_body(subject_of(plain), ACCEPTED_FOOTERS)),
            )

    def test_a_missing_footer_is_still_refused(self) -> None:
        """The URL line is not a footer."""
        assert_that(body_findings(BODY + URL_AFTER), equal_to(1))

    def test_prose_mention_is_not_stripped(self) -> None:
        """A footer followed by prose still passes; prose alone is no footer."""
        kept = BODY + ROBOT + "\n" + PROSE + "\n"
        assert_that(body_findings(kept), equal_to(0))
        assert_that(body_findings(BODY + PROSE + "\n"), equal_to(1))

    def test_url_first_line_is_absent(self) -> None:
        """The first line is the first line that is not the URL."""
        assert_that(
            forms.pr_body(subject_of(SESSION + "\nFixes #1\n"), []),
            equal_to(forms.pr_body(subject_of("Fixes #1\n"), [])),
        )


class TestReviews(unittest.TestCase):
    """A review comment reads the same with or without the session URL."""

    def test_review_form_checks(self) -> None:
        """The ordinary and the gated form check read it as without."""
        text = f"## Adversarial review\n\nReviewed: {HEAD}\nVerdict: approved\n"
        for variant in (text + URL_AFTER, text + FOOTER_LINK + "\n"):
            for check in (forms.ordinary_review, forms.gated_review):
                assert_that(
                    check(subject_of(variant), GATED),
                    equal_to(check(subject_of(text), GATED)),
                )

    def test_review_forms_read_the_first_and_ending_lines_without_the_url(
        self,
    ) -> None:
        """The URL first line and the footer link do not change either form check."""
        ended = dataclasses.replace(GATED, lines=(*GATED.lines, "---", FOOTER))
        head = f"## Adversarial review\nReviewed: {HEAD}\nVerdict: approved\n"
        ending = f"---\n{FOOTER}\n"
        ending_link = f"---\n{FOOTER_LINK}\n"
        for check in (forms.ordinary_review, forms.gated_review):
            assert_that(check(subject_of(head + ending), ended), equal_to([]))
            assert_that(
                check(subject_of(f"{SESSION}\n{head}"), GATED),
                equal_to(check(subject_of(head), GATED)),
            )
            assert_that(
                check(subject_of(head + ending_link), ended),
                equal_to(check(subject_of(head + ending), ended)),
            )

    def test_readers(self) -> None:
        """Both readers find a review with the URL line first, or in brackets."""
        for read in (reviews.read_comment, reviews.read_gated):
            plain = read(REVIEW_TEXT, REVIEW_FORM)
            assert_that(plain is None, equal_to(False))
            for text in (f"{SESSION}\n{REVIEW_TEXT}", f"{REVIEW_TEXT}<{SESSION}>\n"):
                assert_that(read(text, REVIEW_FORM), equal_to(plain))

    def test_plain_check_ignores_angle_brackets_of_the_url_line(self) -> None:
        """``<URL>`` on its own line is not HTML."""
        assert_that(reviews.is_plain(f"a\n<{SESSION}>\n"), equal_to(True))
        assert_that(reviews.is_plain(f"a\n<b>{SESSION}\n"), equal_to(False))

    def test_a_review_attempt_after_the_url_line_is_seen(self) -> None:
        """A comment that tries to be a review is one whatever line the URL is."""
        attempt = shapes.Comment(
            body=f"{SESSION}\n## Re-review: approved\n",
            author_association="MEMBER",
            created_at="2",
            url="u",
        )
        rules = reviews.rules(REVIEW_CONFIG, "o/x")
        unread = unreadableform.unread([attempt], REVIEW_CONFIG.trusted, rules, "")
        assert_that(unread, equal_to("2"))

    def test_grade_lines_need_no_stripping(self) -> None:
        """A grade is a line of its own, so the URL line changes none."""
        text = f"{SESSION}\n{REVIEW_TEXT}Plan: approved\nExecution: changes needed\n"
        comment = shapes.Comment(
            body=text, author_association="MEMBER", created_at="2", url="u"
        )
        (found,) = reviews.from_comments(
            [comment], REVIEW_CONFIG.trusted, reviews.read_comment, REVIEW_FORM
        )
        assert_that(found.plan_approved, equal_to(True))

    def test_ruling_first_line(self) -> None:
        """The first line of a ruling is the first line that is not the URL."""
        ruling = f"{SESSION}\nOpus ruling\nx\n"
        assert_that(flow.is_ruling(ruling), equal_to(True))
        assert_that(flow.is_ruling(f"{PROSE}\nOpus ruling\n"), equal_to(False))

    def test_ruling_second_line(self) -> None:
        """The ruling word is on the line after ``Opus ruling``, URL line or not."""
        plain = "Opus ruling\nRuling: split\n"
        for text in (f"{SESSION}\n{plain}", f"Opus ruling\n{SESSION}\nRuling: split\n"):
            assert_that(rulings.read_ruling(text), equal_to(rulings.Ruling.SPLIT))
        assert_that(rulings.read_ruling(plain), equal_to(rulings.Ruling.SPLIT))


def lint_with_phrase(*argv: str) -> tuple[object, str]:
    """Run ``pitboss lint`` with the one banned phrase of these tests.

    Args:
        *argv: the arguments after ``lint``; the phrase options are added.

    Returns:
        The exit code and what it printed.
    """
    phrase_file = write_text("phrases.tsv", BANNED)
    ran = lint(*argv, "--phrases", phrase_file, "--no-default-phrases")
    return ran.code, ran.out


def event_code(body: str) -> tuple[object, str]:
    """Run ``pitboss lint event`` on a pull request body.

    Args:
        body: the pull request's body.

    Returns:
        The exit code and the status state it wrote.
    """
    pull = {"body": body, "head": {"sha": HEAD, "ref": "x"}, "user": {"login": "me"}}
    event = write_text("event.json", json.dumps({"pull_request": pull}))
    status = write_text("status.json", "")
    code, _ = lint_with_phrase("event", event, status)
    with open(status, encoding="utf-8") as written:
        return code, json.load(written)["state"]


class TestLint(unittest.TestCase):
    """The phrases of ``lint`` are searched in the text without the session URL."""

    def test_form_kinds_search_phrases_without_the_url(self) -> None:
        """A banned phrase in the URL line alone is no finding of ``pr-body``."""
        code, shown = lint_with_phrase("pr-body", write_text("b.md", BODY + URL_AFTER))
        assert_that((code, shown), equal_to((0, "ok\n")))
        _, found = lint_with_phrase("pr-body", write_text("b.md", BODY + PROSE))
        assert_that(found, contains_string("session-line"))

    def test_event_searches_phrases_without_the_url(self) -> None:
        """A banned phrase in the URL line alone is no finding of ``event``."""
        assert_that(event_code(BODY + URL_AFTER), equal_to((0, "success")))
        assert_that(event_code(BODY + PROSE + "\n")[1], not_(equal_to("success")))


class TestUnreadable(unittest.TestCase):
    """UNREADABLE REVIEW does not see the session URL."""

    def test_url_line_does_not_change_the_first_line(self) -> None:
        """A review in the form stays readable, one off it stays unreadable."""
        assert_that(unreadable_count(IN_FORM + URL_AFTER), equal_to(0))
        assert_that(unreadable_count(SESSION + "\n" + IN_FORM), equal_to(0))
        assert_that(unreadable_count(OFF_FORM + URL_AFTER), equal_to(1))

    def test_a_comment_of_only_the_url_is_no_review(self) -> None:
        """It grades nothing."""
        assert_that(unreadable_count(SESSION + "\n"), equal_to(0))
