"""The Plan holds the ticket body's Done-when, item by item, each in a row (#396)."""

import itertools
import unittest
from typing import Mapping, Sequence

from hamcrest import assert_that, contains_string, equal_to

from .. import plandonewhen, ticketwhen

RULE = "meet the Done-when as written, or prove it impossible"
FOOTER = "\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
TWO = "Text.\n\n## Done when\n\n- First item.\n- Second item.\n"
# each case: the ticket and the items its Done-when has, in order
ITEMS: Mapping[str, tuple[str, Sequence[str]]] = {
    "bullets with dashes": (TWO, ["First item.", "Second item."]),
    "bullets with stars and plus signs": (
        "Done-when:\n* one\n+ two\n",
        ["one", "two"],
    ),
    "numbered bullets": ("Done-when:\n1. one\n2) two\n", ["one", "two"]),
    "a bullet wrapped over lines": (
        "Done-when:\n- one that\n  goes on\n- two\n",
        ["one that goes on", "two"],
    ),
    "a bullet with a bullet under it": (
        "Done-when:\n- one\n  - under it\n- two\n",
        ["one - under it", "two"],
    ),
    "a paragraph of lines is one item": (
        "Done-when: first\nsecond\n\nthird\n",
        ["first second", "third"],
    ),
    "the heading's own line comes first": (
        "Done-when: `a` is `b`\nmore\n\nElse",
        ["`a` is `b` more", "Else"],
    ),
    "the footer ends the section": (TWO + FOOTER, ["First item.", "Second item."]),
    "no section": ("Text only.", []),
    "a paragraph after the bullets is an item of the body": (
        TWO + "\nAnd a third item.\n",
        ["First item.", "Second item.", "And a third item."],
    ),
}
ROWS = "## Plan\n1. First item. `git status`\n2. Second item. `git log`\n"
# each case: the Plan, the words of the finding expected (none: it passes)
PLANS: Mapping[str, tuple[str, Sequence[str]]] = {
    "each item in a row of its own": (ROWS, []),
    "an item wrapped over lines": (
        "## Plan\n1. First\nitem. `git status`\n2. Second item. `git log`\n",
        [],
    ),
    "the rows in another order": (
        "## Plan\n1. Second item. `git log`\n2. First item. `git status`\n",
        [],
    ),
    "an item narrowed": (
        "## Plan\n1. First item. `git status`\n2. Second. `git log`\n",
        ["Second item."],
    ),
    "an item reworded": (
        "## Plan\n1. First item! `git status`\n2. Second item. `git log`\n",
        ["First item.", "is not in the Plan word for word"],
    ),
    "an item missing": ("## Plan\n1. First item. `git status`\n", ["Second item."]),
    "the items in prose and not in a row": (
        "## Plan\nFirst item.\nSecond item.\n1. `git status`\n",
        ["First item.", "is not in a numbered Plan row"],
    ),
    "two items in one row": (
        "## Plan\n1. First item. Second item. `git status`\n",
        ["Second item.", "shares its numbered Plan row"],
    ),
    "no Plan": ("", ["First item."]),
}


class TestItems(unittest.TestCase):
    """The items of a ticket's Done-when, and the digest that records them."""

    def test_each_case(self) -> None:
        """Done-when: bullets of each marker, wrapped, nested, paragraphs, comments."""
        for name, (ticket, items) in ITEMS.items():
            with self.subTest(name):
                assert_that(list(ticketwhen.items(ticket)), equal_to(list(items)))

    def test_the_digest_follows_the_items_alone(self) -> None:
        """Done-when: another item changes it, other text of the body does not."""
        base = ticketwhen.digest(TWO)
        other = ticketwhen.digest(TWO.replace("First", "Third"))
        outside = ticketwhen.digest("More text.\n" + TWO + "\n## Notes\nx\n")
        assert_that([base == other, base == outside], equal_to([False, True]))
        assert_that(len(base), equal_to(16))
        assert_that(ticketwhen.digest("Text only."), equal_to(""))


class TestFindings(unittest.TestCase):
    """The Plan holds each item word for word, in a numbered row of its own."""

    def test_each_case(self) -> None:
        """Done-when: a missing, reworded or narrowed item is refused."""
        for name, (plan, words) in PLANS.items():
            with self.subTest(name):
                found = plandonewhen.findings(plan, TWO)
                assert_that(len(found), equal_to(1 if words else 0))
                for word in words:
                    assert_that(found[0], contains_string(word))
                for each in found:
                    assert_that(each, contains_string(RULE))
                    assert_that(each.startswith("plan-done-when:"), equal_to(True))

    def test_the_rule_is_meet_it_or_prove_it_impossible(self) -> None:
        """Done-when: the refusal offers no hand back."""
        assert_that(plandonewhen.RULE, equal_to(RULE))
        found = plandonewhen.findings("nothing", TWO)[0]
        for word in ("NOT PROCEEDING", "NOT STARTED", "hand back", "escalate"):
            assert_that(word in found, equal_to(False))


def measured(verb: str, preposition: str, command: str) -> str:
    """A ticket whose one Done-when item names a measurement.

    Args:
        verb: the word before the preposition.
        preposition: the word before the command.
        command: the command.

    Returns:
        The ticket.
    """
    return f"Done-when:\n- The count of x, {verb} {preposition} `{command}`, is 3.\n"


def row_of(ticket: str, own: str) -> str:
    """A Plan whose one row copies the ticket's item and adds its own text.

    Args:
        ticket: the ticket.
        own: the text after the copy.

    Returns:
        The Plan section.
    """
    return f"## Plan\n1. {ticketwhen.items(ticket)[0]} {own}\n"


MEASURE = "rg -c x src"
SPELLINGS = list(itertools.product(plandonewhen.VERBS, plandonewhen.PREPOSITIONS))


class TestMeasurement(unittest.TestCase):
    """A measurement the Done-when names is the command the row runs."""

    def test_each_spelling_is_read(self) -> None:
        """Done-when: each verb with each preposition names the measurement."""
        for verb, preposition in SPELLINGS:
            with self.subTest(verb=verb, preposition=preposition):
                item = ticketwhen.items(measured(verb, preposition, MEASURE))[0]
                assert_that(plandonewhen.measurements(item), equal_to([MEASURE]))

    def test_each_spelling_is_refused_when_the_row_runs_another(self) -> None:
        """Done-when: a substitute is refused, whatever the spelling."""
        for verb, preposition in SPELLINGS:
            with self.subTest(verb=verb, preposition=preposition):
                ticket = measured(verb, preposition, MEASURE)
                found = plandonewhen.findings(row_of(ticket, "`rg -c y src`"), ticket)
                assert_that(len(found), equal_to(1))
                assert_that(found[0], contains_string(f"`{MEASURE}`"))
                assert_that(found[0].startswith("plan-measurement:"), equal_to(True))

    def test_each_spelling_passes_when_the_row_runs_it(self) -> None:
        """Done-when: the command itself, or piped into more, in the row."""
        for verb, preposition in SPELLINGS:
            for own in (f"`{MEASURE}`", f"`{MEASURE} | wc -l`"):
                with self.subTest(verb=verb, preposition=preposition, own=own):
                    ticket = measured(verb, preposition, MEASURE)
                    found = plandonewhen.findings(row_of(ticket, own), ticket)
                    assert_that(list(found), equal_to([]))

    def test_the_copy_alone_is_not_running_it(self) -> None:
        """Done-when: the command inside the copied item is not the row's own."""
        ticket = measured("measured", "by", MEASURE)
        for own in ("`git status`", ""):
            with self.subTest(own=own):
                found = plandonewhen.findings(row_of(ticket, own), ticket)
                assert_that(len(found), equal_to(1))
                assert_that(found[0], contains_string("plan-measurement:"))

    def test_the_letters_of_the_words_may_be_any_case(self) -> None:
        """Done-when: `Measured By` names it as `measured by` does."""
        ticket = measured("Measured", "By", MEASURE)
        item = ticketwhen.items(ticket)[0]
        assert_that(plandonewhen.measurements(item), equal_to([MEASURE]))

    def test_what_is_not_a_measurement_is_not_asked_for(self) -> None:
        """Done-when: a command named otherwise, or after another word."""
        for ticket in (
            "Done-when:\n- `rg -c x src` is removed.\n",
            measured("measured", "on", MEASURE),
            measured("run", "by", MEASURE),
            "Done-when:\n- measured by the count of `src`.\n",
        ):
            with self.subTest(ticket):
                found = plandonewhen.findings(row_of(ticket, "`git status`"), ticket)
                assert_that(list(found), equal_to([]))


DIGEST = ticketwhen.digest(TWO)
OTHER = "f" * 16
# each case: the body's lines and the words of the finding expected (none: it passes)
BODIES: Mapping[str, tuple[str, Sequence[str]]] = {
    "the digest of the ticket": (f"Done-when digest: {DIGEST}\n", []),
    "the digest of the ticket twice": (
        f"Done-when digest: {OTHER}\nDone-when digest: {DIGEST}\n",
        [],
    ),
    "the digest of the ticket with trailing blanks": (
        f"Done-when digest: {DIGEST}  \n",
        [],
    ),
    "another digest": (
        f"Done-when digest: {OTHER}\n",
        ["edited after a worker started", OTHER, DIGEST],
    ),
    "the other digest last": (
        f"Done-when digest: {DIGEST}\nDone-when digest: {OTHER}\n",
        ["edited after a worker started", OTHER],
    ),
    "no line": ("Fixes #1\n", ["no `Done-when digest: " + DIGEST + "`"]),
    "a line that is no digest": (
        "Done-when digest: abc\n",
        ["no `Done-when digest: " + DIGEST + "`"],
    ),
    "a digest in the middle of a line": (
        f"See Done-when digest: {DIGEST} here\n",
        ["no `Done-when digest: " + DIGEST + "`"],
    ),
}


class TestEdited(unittest.TestCase):
    """A Done-when edited after a worker started is found and refused."""

    def test_each_case(self) -> None:
        """Done-when: the body records the digest of the start."""
        for name, (body, words) in BODIES.items():
            with self.subTest(name):
                found = plandonewhen.edited(body, TWO)
                assert_that(len(found), equal_to(1 if words else 0))
                for word in words:
                    assert_that(found[0], contains_string(word))
                for each in found:
                    assert_that(each.startswith("done-when-edited:"), equal_to(True))

    def test_a_ticket_with_no_done_when_has_nothing_to_edit(self) -> None:
        """Done-when: no section, no digest, no finding."""
        assert_that(list(plandonewhen.edited("Fixes #1\n", "Text only.")), equal_to([]))


INTERPRETED = (
    "Fixes #1\n\n## Plan\nThe plan.\n\n## Execution\n"
    "Interpretation of Done-when item 3: it means less.\n\nDone.\n"
)
NOT_INTERPRETED = (
    "## Plan\nThe plan interprets the argument.\n\n"
    "```\nthe interpreted Done-when\n```\n\n## Notes\nInterpretation of"
    " Done-when item 1\n\n## Execution\nDone.\n"
)


class TestInterpretation(unittest.TestCase):
    """An Interpretation of a Done-when item is refused."""

    def test_an_interpretation_is_refused_and_other_words_pass(self) -> None:
        """Done-when: the Execution's Interpretation of an item."""
        refused = plandonewhen.interpretations(INTERPRETED)
        passed = plandonewhen.interpretations(NOT_INTERPRETED)
        assert_that(len(refused), equal_to(1))
        assert_that(refused[0], contains_string(RULE))
        for word in ("NOT PROCEEDING", "NOT STARTED", "hand back", "escalate"):
            assert_that(word in refused[0], equal_to(False))
        assert_that(passed, equal_to([]))
